from __future__ import annotations

import argparse
import os

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPClassifier

HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(HERE, "full_dataset_with_scores_new.csv")
EMB_DIR = os.path.join(HERE, "all_embeddings")
DEFAULT_OUT = os.path.join(HERE, "outputs", "tier_probe_llm")

MODELS = {
    "bge":             ("embeddings_bge.npy",              "BGE-large-en-v1.5",    "encoder"),
    "mpnet":           ("embeddings_mpnet.npy",            "MPNet-base-v2",        "encoder"),
    "minilm":          ("embeddings_miniLM.npy",           "MiniLM-L6-v2",         "encoder"),
    "qwen_embedding":  ("embeddings_qwen_embeddings.npy",  "Qwen3-Embedding-0.6B", "encoder"),
    "qwen2.5_3b_L24":  ("embeddings_qwen2.5_3B_L24.npy",   "Qwen2.5-3B L24",       "llm"),
    "qwen2.5_7b_L20":  ("embeddings_qwen2.5_7b_L20.npy",   "Qwen2.5-7B L20",       "llm"),
    "qwen2.5_14b_L24": ("embeddings_qwen2.5_14B_L24.npy",  "Qwen2.5-14B L24",      "llm"),
    "llama3.1_8b_L16": ("embeddings_llama3.1_8B_L16.npy",  "Llama-3.1-8B L16",     "llm"),
    "gemma2_9b_L29":   ("embeddings_gemma2_9B_L29.npy",    "Gemma-2-9B L29",       "llm"),
    "gemma2_27b_L28":  ("embeddings_gemma2_27B_L28.npy",   "Gemma-2-27B L28",      "llm"),
}

TIER_ORDER = ["Collapse", "Striving", "Conflict", "Activation", "Growth", "Clarity", "Unity"]
TIER_ALIASES = {"Shadow": "Collapse", "Unconscious / Collapse": "Collapse",
                "Highly Contracted / Self-Destructive": "Collapse"}
N_SPLITS = 30
TEST_SIZE = 0.2
METRICS = ["logreg_acc", "logreg_f1", "mlp_acc", "mlp_f1"]


def load_df(path):
    df = pd.read_csv(path)
    df = df.dropna(subset=["sentence", "score", "tier"]).reset_index(drop=True)
    df["score"] = pd.to_numeric(df["score"], errors="coerce")
    df = df.dropna(subset=["score"]).reset_index(drop=True)
    return df


def tier_labels(df):
    def idx(t):
        t = TIER_ALIASES.get(str(t).strip(), str(t).strip())
        if t not in TIER_ORDER:
            raise ValueError(f"unknown tier {t!r}")
        return TIER_ORDER.index(t)
    return df["tier"].apply(idx).values


def run_for_model(key, y):
    fname, name, group = MODELS[key]
    print(f"\n==================== {name} ({key}) ====================")
    X = np.load(os.path.join(EMB_DIR, fname))
    if len(X) != len(y):
        raise ValueError(f"{key}: {len(X)} embeddings vs {len(y)} rows")
    rows = []
    for seed in range(N_SPLITS):
        np.random.seed(seed)
        Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=TEST_SIZE, random_state=seed, stratify=y)
        p = LogisticRegression(max_iter=2000).fit(Xtr, ytr).predict(Xte)
        q = MLPClassifier(hidden_layer_sizes=(128, 64), activation="relu", solver="adam", alpha=1e-4,
                          learning_rate_init=1e-3, max_iter=2000, random_state=seed, early_stopping=True,
                          n_iter_no_change=20, validation_fraction=0.1).fit(Xtr, ytr).predict(Xte)
        rows.append({"model": key, "split": seed,
                     "logreg_acc": accuracy_score(yte, p), "logreg_f1": f1_score(yte, p, average="weighted"),
                     "mlp_acc": accuracy_score(yte, q), "mlp_f1": f1_score(yte, q, average="weighted")})
        if (seed + 1) % 10 == 0:
            print(f"  split {seed + 1}/{N_SPLITS}")
    long = pd.DataFrame(rows)
    summ = {"model": key, "display_name": name, "group": group}
    for m in METRICS:
        summ[f"{m}_mean"] = float(long[m].mean())
        summ[f"{m}_std"] = float(long[m].std(ddof=1))
    return summ, long


def write_tex(summary, path):
    L = ["% Generated by 2c_tier_probe_llm.py -- do not edit by hand",
         "% needs \\usepackage{booktabs}",
         "\\begin{table}[!htbp]", "\\centering", "\\small",
         f"\\caption{{Tier classification probe performance averaged over {N_SPLITS} stratified "
         "train--test splits. LLM rows are residual-stream activations at the steering layer (e.g., "
         "L24 = layer 24), not sentence-embedding models. Bold: best within each group.}",
         "\\label{tab:tier_classification}",
         "\\begin{tabular}{lcccc}", "\\toprule",
         " & \\multicolumn{2}{c}{Logistic Regression} & \\multicolumn{2}{c}{MLP (128,64)} \\\\",
         "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
         "Representation & Accuracy $\\uparrow$ & Weighted F1 $\\uparrow$ & Accuracy $\\uparrow$ & "
         "Weighted F1 $\\uparrow$ \\\\", "\\midrule"]
    summary = summary.reset_index(drop=True)
    best = {g: {m: summary[summary.group == g][f"{m}_mean"].max() for m in METRICS}
            for g in summary.group.unique()}
    for i, r in summary.iterrows():
        cells = []
        for m in METRICS:
            v = r[f"{m}_mean"]
            s = f"{v:.3f}"
            cells.append(f"\\textbf{{{s}}}" if abs(v - best[r.group][m]) < 5e-4 else s)
        L.append(f"{r.display_name} & " + " & ".join(cells) + " \\\\")
        if i < len(summary) - 1 and summary.loc[i + 1, "group"] != r.group:
            L.append("\\midrule")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", nargs="+", default=None, choices=list(MODELS))
    ap.add_argument("--group", choices=["encoder", "llm"], default=None)
    ap.add_argument("--out-dir", default=DEFAULT_OUT)
    args = ap.parse_args()
    os.makedirs(args.out_dir, exist_ok=True)
    y = tier_labels(load_df(CSV_PATH))
    keys = [k for k in MODELS if (args.models is None or k in args.models)
            and (args.group is None or MODELS[k][2] == args.group)]
    summ, longs = [], []
    for k in keys:
        s, l = run_for_model(k, y)
        summ.append(s); longs.append(l)
    summary = pd.DataFrame(summ)
    summary.to_csv(os.path.join(args.out_dir, "tier_probe_llm_summary.csv"), index=False)
    pd.concat(longs).to_csv(os.path.join(args.out_dir, "tier_probe_llm_all_splits.csv"), index=False)
    write_tex(summary, os.path.join(args.out_dir, "tier_probe_llm_table.tex"))
    print("\n===== SUMMARY =====")
    print(summary[["display_name"] + [f"{m}_mean" for m in METRICS]].to_string(
        index=False, float_format=lambda v: f"{v:.3f}"))
    print(f"\n[Saved] {args.out_dir}")


if __name__ == "__main__":
    main()
