from __future__ import annotations

import argparse
import csv
import json
import math
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent

MODELS = [
    ("qwen_3b_L24",    "Qwen2.5-3B"),
    ("qwen_7b_L20",    "Qwen2.5-7B"),
    ("qwen_14b_L24",   "Qwen2.5-14B"),
    ("llama_8b_L16",   "Llama-3.1-8B"),
    ("gemma_9b_L29",   "Gemma-2-9B"),
    ("gemma2_27b_L28", "Gemma-2-27B"),
]
ALPHAS = [0.1, 0.2, 0.3, 0.5]
BREAKDOWN = {("gemma2_27b_L28", 0.5)}
BREAKDOWN_LABEL = "output breakdown (see caption)"
METHODS = ("global_ridge", "local_manifold")
STYLE = {
    "baseline":       dict(color="#7f7f7f", ls="--", lw=1.0, label="baseline (no steering)"),
    "global_ridge":   dict(color="#d62728", ls="-", lw=1.2, marker="X", ms=4.0, label="global_ridge"),
    "local_manifold": dict(color="#2ca02c", ls="-", lw=1.6, marker="s", ms=3.0, label="local_manifold"),
}
TEXTWIDTH_IN = 5.5


def _alpha(a):
    return None if a in (None, "", "None") else round(float(a), 3)


def load_triviaqa(path: Path):
    out = {}
    with open(path) as f:
        for row in csv.DictReader(f):
            out[(row["condition"].strip(), _alpha(row.get("alpha")))] = float(row["accuracy_pct"])
    return out


def load_longform(path: Path):
    rates, judges = defaultdict(list), set()
    with open(path) as f:
        for line in f:
            if not line.strip():
                continue
            r = json.loads(line)
            j = r.get("judge_result") or {}
            judges.add(j.get("judge_model"))
            x = j.get("factuality_rate")
            if isinstance(x, (int, float)) and not math.isnan(x):
                rates[(r["condition"], _alpha(r.get("alpha")))].append(x)
    return {k: sum(v) / len(v) for k, v in rates.items()}, {k: len(v) for k, v in rates.items()}, judges


def draw_panel(ax, data, n=None, min_frac=0.5, n_total=50, flag=()):
    b = data.get(("baseline", None))
    if b is not None:
        s = STYLE["baseline"]
        ax.axhline(b, color=s["color"], ls=s["ls"], lw=s["lw"], zorder=1.5, label=s["label"])
    for m in METHODS:
        s = STYLE[m]
        xs = [a for a in ALPHAS if (m, a) in data]
        ys = [data[(m, a)] for a in xs]
        low = {a for a in xs if a in flag}
        if n is not None:
            low |= {a for a in xs if n.get((m, a), n_total) < min_frac * n_total}
        k = next((i for i, a in enumerate(xs) if a in low), len(xs))
        ax.plot(xs[:k], ys[:k], color=s["color"], ls=s["ls"], lw=s["lw"],
                marker=s["marker"], ms=s["ms"], label=s["label"], zorder=3)
        if k < len(xs):
            ax.plot(xs[max(k - 1, 0):], ys[max(k - 1, 0):], color=s["color"], ls=(0, (3, 2)),
                    lw=s["lw"], zorder=3)
            ax.plot(xs[k:], ys[k:], ls="none", marker=s["marker"], ms=s["ms"] + 0.6,
                    mfc="white", mec=s["color"], mew=0.9, zorder=4)
    ax.set_xticks(ALPHAS)
    ax.set_xticklabels([f"{a:g}".lstrip("0") for a in ALPHAS])
    ax.set_xlim(0.05, 0.55)
    ax.grid(True, alpha=0.3, lw=0.4, zorder=0)
    ax.tick_params(length=2, pad=1.5)


def write_tex(tqa, lf, lf_n, path: Path, n_total=50):
    na = len(ALPHAS)
    ah = " & ".join(f"{a:g}" for a in ALPHAS)
    L = ["% Generated by 20b_plot_multimodel_factuality.py -- do not edit by hand",
         "% needs \\usepackage{booktabs,multirow,graphicx}",
         "\\begin{table}[t]", "\\centering", "\\small",
         "\\caption{Factuality by steering strength $\\alpha$. TriviaQA: accuracy (\\%, $n{=}500$, greedy). "
         "Long-form: mean claim-level factuality rate over scorable responses ($n{=}50$ per cell). "
         "$^\\dagger$Output breakdown (Gemma-2-27B, $\\alpha{=}0.5$); subscripts give the number of "
         "scorable long-form responses where fewer than half were scorable.}",
         "\\label{tab:factuality_by_alpha}",
         "\\resizebox{\\linewidth}{!}{%",
         "\\begin{tabular}{ll" + "c" * na + "c" + "c" * na + "}", "\\toprule",
         f" & & \\multicolumn{{{na}}}{{c}}{{TriviaQA acc.\\ (\\%)}} & & "
         f"\\multicolumn{{{na}}}{{c}}{{Long-form factuality}} \\\\",
         f"\\cmidrule{{3-{2 + na}}} \\cmidrule{{{4 + na}-{3 + 2 * na}}}",
         f"Model & Method & {ah} & & {ah} \\\\", "\\midrule"]
    names = dict(MODELS)
    for k, (tag, name) in enumerate(MODELS):
        flag = {a for (t, a) in BREAKDOWN if t == tag}
        bt, bl = tqa[tag][("baseline", None)], lf[tag][("baseline", None)]
        L.append(f"\\multirow{{3}}{{*}}{{{name}}} & baseline & "
                 f"\\multicolumn{{{na}}}{{c}}{{{bt:.1f}}} & & \\multicolumn{{{na}}}{{c}}{{{bl:.3f}}} \\\\")
        for m in METHODS:
            tc, lc = [], []
            for a in ALPHAS:
                dag = "$^\\dagger$" if a in flag else ""
                tc.append(f"{tqa[tag][(m, a)]:.1f}{dag}")
                n = lf_n[tag].get((m, a), n_total)
                sub = f"$_{{({n})}}$" if n < 0.5 * n_total else ""
                lc.append(f"{lf[tag][(m, a)]:.3f}{dag}{sub}")
            mname = "\\texttt{" + m.replace("_", "\\_") + "}"
            L.append(f" & {mname} & " + " & ".join(tc) + " & & " + " & ".join(lc) + " \\\\")
        if k < len(MODELS) - 1:
            L.append("\\midrule")
    L += ["\\bottomrule", "\\end{tabular}}", "\\end{table}"]
    path.write_text("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tqa-dir", default=str(HERE / "all_triviaqa"))
    ap.add_argument("--lf-dir", default=str(HERE / "all_long_form_judged"))
    ap.add_argument("--out-dir", default=str(HERE / "outputs" / "figures_multimodel"))
    ap.add_argument("--tqa-ylim", type=float, nargs=2, default=None)
    ap.add_argument("--lf-ylim", type=float, nargs=2, default=None)
    args = ap.parse_args()

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    tqa, lf, lf_n, all_judges = {}, {}, {}, set()
    for tag, _ in MODELS:
        tqa[tag] = load_triviaqa(Path(args.tqa_dir) / f"triviaqa_accuracy_{tag}.csv")
        lf[tag], lf_n[tag], j = load_longform(Path(args.lf_dir) / f"factuality_longform_{tag}_judged.jsonl")
        all_judges |= j
    if len(all_judges) != 1:
        print(f"WARNING: long-form files use different judges {all_judges} -- rates not comparable across models")

    plt.rcParams.update({"font.size": 7, "axes.titlesize": 7, "axes.labelsize": 7,
                         "xtick.labelsize": 6, "ytick.labelsize": 6, "legend.fontsize": 6.5,
                         "pdf.fonttype": 42, "ps.fonttype": 42})
    fig, axs = plt.subplots(2, len(MODELS), figsize=(TEXTWIDTH_IN, 2.6), sharex=True, sharey="row")
    rows = [(tqa, "TriviaQA\nacc. (%)", args.tqa_ylim), (lf, "Long-form\nfactuality rate", args.lf_ylim)]
    for i, (data, ylabel, ylim) in enumerate(rows):
        for j, (tag, title) in enumerate(MODELS):
            ax = axs[i, j]
            draw_panel(ax, data[tag], n=lf_n[tag] if i == 1 else None,
                       flag={a for (t, a) in BREAKDOWN if t == tag})
            if i == 0:
                ax.set_title(title, pad=3)
            if j == 0:
                ax.set_ylabel(ylabel)
        if ylim:
            axs[i, 0].set_ylim(*ylim)
    fig.align_ylabels(axs[:, 0])
    fig.supxlabel(r"steering strength $\alpha$", fontsize=7, y=0.02)
    fig.tight_layout(pad=0.3, w_pad=0.15, h_pad=0.3, rect=(0, 0.03, 1, 0.91))
    h, l = axs[0, 0].get_legend_handles_labels()
    order = [STYLE[k]["label"] for k in ("baseline", "global_ridge", "local_manifold")]
    hl = dict(zip(l, h))
    from matplotlib.lines import Line2D
    proxy = Line2D([], [], color="0.35", ls=(0, (3, 2)), lw=1.2, marker="s", ms=3.4,
                   mfc="white", mec="0.35", mew=0.9)
    fig.legend([hl[x] for x in order] + [proxy], order + [BREAKDOWN_LABEL],
               loc="upper center", ncol=4, frameon=False,
               bbox_to_anchor=(0.5, 1.0), handlelength=2.2, columnspacing=1.2)

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    fig.savefig(out / "factuality_multimodel.pdf", bbox_inches="tight")
    fig.savefig(out / "factuality_multimodel.png", dpi=300, bbox_inches="tight")

    with open(out / "factuality_multimodel_summary.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["model", "condition", "alpha", "triviaqa_em_pct", "longform_fact_rate", "longform_n"])
        for tag, title in MODELS:
            keys = [("baseline", None)] + [(m, a) for m in METHODS for a in ALPHAS]
            for k in keys:
                lv = lf[tag].get(k)
                w.writerow([title, k[0], "" if k[1] is None else k[1], tqa[tag].get(k, ""),
                            "" if lv is None else f"{lv:.4f}", lf_n[tag].get(k, "")])
    write_tex(tqa, lf, lf_n, out / "factuality_multimodel_table.tex")
    print(f"judge(s): {all_judges}")
    print(f"wrote: {out / 'factuality_multimodel.pdf'}")


if __name__ == "__main__":
    main()
